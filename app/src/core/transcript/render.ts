// The generated companions of transcript.json (folder spec §8.8), byte-exact: `transcript.md` (a header,
// then one paragraph per speaker turn) and `transcript.vtt` (one cue per segment, cue id = segment id).
// Also the paragraph rule the lecture view shares, and a plain-text export.
import type { Lang } from '../model/ids';
import type { LectureFile, Segment, TranscriptFile } from '../model/files';
import { clock } from '../speech/timing';
import { engineLabel, labelOf, recordedByLabel } from './labels';

/** A paragraph joins segments of one speaker while the gap stays under this… */
export const PARAGRAPH_GAP_MS = 2_000;
/** …and the paragraph stays within this long. */
export const PARAGRAPH_MAX_MS = 60_000;

export interface Paragraph { speaker: string; startMs: number; endMs: number; segments: Segment[] }

const byTime = (a: Segment, b: Segment) => a.startMs - b.startMs || a.endMs - b.endMs;

/**
 * Consecutive segments of the same speaker, until a gap of 2 s or more, or until the paragraph would
 * last more than 60 s (a single longer segment is a paragraph of its own). Shared by transcript.md and
 * the lecture view (UX §3.5.3).
 */
export function paragraphs(t: Pick<TranscriptFile, 'segments'>): Paragraph[] {
  const out: Paragraph[] = [];
  let cur: Paragraph | null = null;
  for (const s of [...t.segments].sort(byTime)) {
    if (cur && s.speaker === cur.speaker && s.startMs - cur.endMs < PARAGRAPH_GAP_MS && s.endMs - cur.startMs <= PARAGRAPH_MAX_MS) {
      cur.segments.push(s);
      cur.endMs = Math.max(cur.endMs, s.endMs);
      continue;
    }
    cur = { speaker: s.speaker, startMs: s.startMs, endMs: s.endMs, segments: [s] };
    out.push(cur);
  }
  return out;
}

const two = (n: number) => String(n).padStart(2, '0');

/** `HH:MM:SS` (whole seconds, floor), as in `[00:41:12]`. */
export function hms(ms: number): string {
  const s = Math.max(0, Math.floor(ms / 1000));
  return `${two(Math.floor(s / 3600))}:${two(Math.floor((s % 3600) / 60))}:${two(s % 60)}`;
}

/** `HH:MM:SS.mmm`, the WebVTT timestamp. */
export function vttTime(ms: number): string {
  const v = Math.max(0, Math.round(ms));
  return `${hms(v)}.${String(v % 1000).padStart(3, '0')}`;
}

/** WebVTT cue text: `&`, `<`, `>` escaped; `-->` therefore becomes `--&gt;`. */
export function vttEscape(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/** A cue payload is one line: newlines inside a segment would end the cue. */
const oneLine = (s: string) => s.replace(/\s*[\r\n]+\s*/g, ' ');

const paragraphText = (p: Paragraph) => p.segments.map((s) => oneLine(s.text).trim()).filter((x) => x !== '').join(' ');

/**
 * transcript.md, exactly as folder spec §8.8:
 *
 *   <!-- Generated by Tramado from transcript.json (revision N). Edits to this file are overwritten. -->
 *   # <lecture title>
 *
 *   *<YYYY-MM-DD> · <h:mm:ss> · <recorded by> <name> · <engine>*
 *
 *   **[HH:MM:SS] <speaker label>:** <paragraph text>
 *
 * The date is the UTC date of `startedAt` (every owner writes the same bytes). `lang` overrides the
 * transcript's language for the labels.
 */
export function renderMarkdown(
  t: Pick<TranscriptFile, 'revision' | 'segments' | 'speakers' | 'language' | 'engine'>,
  lecture: Pick<LectureFile, 'title' | 'startedAt' | 'durationMs' | 'recordedBy'>,
  lang?: Lang,
): string {
  const language = lang ?? t.language;
  const lines: string[] = [
    `<!-- Generated by Tramado from transcript.json (revision ${t.revision}). Edits to this file are overwritten. -->`,
    `# ${oneLine(lecture.title).trim()}`,
    '',
    `*${lecture.startedAt.slice(0, 10)} · ${clock(lecture.durationMs)} · ${recordedByLabel(language)} ${oneLine(lecture.recordedBy.name).trim()} · ${engineLabel(t.engine)}*`,
  ];
  for (const p of paragraphs(t)) {
    const text = paragraphText(p);
    if (!text) continue;
    lines.push('', `**[${hms(p.startMs)}] ${labelOf(t, p.speaker)}:** ${text}`);
  }
  return lines.join('\n') + '\n';
}

/** transcript.vtt, exactly as folder spec §8.8: one cue per segment, the cue id is the segment id. */
export function renderVtt(t: Pick<TranscriptFile, 'segments' | 'speakers' | 'language'>): string {
  const parts = ['WEBVTT', ''];
  for (const s of [...t.segments].sort(byTime)) {
    parts.push(s.id, `${vttTime(s.startMs)} --> ${vttTime(Math.max(s.startMs, s.endMs))}`, `<v ${vttEscape(labelOf(t, s.speaker))}>${vttEscape(oneLine(s.text).trim())}`, '');
  }
  return parts.join('\n');
}

/** Plain text for "Export transcript ▸ .txt": `[HH:MM:SS] Label: text` per paragraph. */
export function renderText(t: Pick<TranscriptFile, 'segments' | 'speakers' | 'language'>, title?: string): string {
  const lines: string[] = title ? [oneLine(title).trim(), ''] : [];
  for (const p of paragraphs(t)) {
    const text = paragraphText(p);
    if (text) lines.push(`[${hms(p.startMs)}] ${labelOf(t, p.speaker)}: ${text}`, '');
  }
  return lines.join('\n');
}
