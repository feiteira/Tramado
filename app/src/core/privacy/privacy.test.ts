import { describe, expect, it } from 'vitest';
import { UI_LOCALES } from '../i18n/languages';
import { groupActivity } from './activity';
import { FLOWS, FLOW_IDS, flowText, privacyFile, privacyMarkdown } from './flows';

describe('privacy flows (UX §3.14.8)', () => {
  it('has one catalog row per flow in every language, with no empty cell', () => {
    expect(FLOWS.map((f) => f.id)).toEqual([...FLOW_IDS]);
    for (const l of UI_LOCALES) {
      for (const f of FLOWS) {
        const r = flowText(f.id, l);
        expect(r.when.trim(), `${l} ${f.id}`).not.toBe('');
        expect(r.what.trim(), `${l} ${f.id}`).not.toBe('');
        expect(r.to.trim(), `${l} ${f.id}`).not.toBe('');
      }
    }
  });

  it('writes one Markdown document per language, linking the others', () => {
    const en = privacyMarkdown('en');
    expect(en.startsWith('# What leaves this computer\n')).toBe(true);
    expect(en).toContain('Generated by `npm run gen:privacy`');
    expect(en).toContain('[Português (Portugal)](PRIVACY.pt.md)');
    expect(en).toContain('| You download a speech model | A download request | Hugging Face |');
    expect(en.split('\n').filter((l) => l.startsWith('| ')).length).toBe(FLOWS.length + 1);
    expect(privacyMarkdown('pt')).toContain('# O que sai deste computador');
    expect(privacyMarkdown('es')).toContain('[English](PRIVACY.md)');
    expect(privacyFile('en')).toBe('PRIVACY.md');
    expect(privacyFile('es')).toBe('PRIVACY.es.md');
  });

  it('names only the places the code talks to', () => {
    const hosts = FLOWS.flatMap((f) => f.hosts).join(' ');
    for (const h of ['openrouter.ai', 'huggingface.co', 'syncthing.net']) expect(hosts).toContain(h);
    expect(hosts).not.toMatch(/google|analytics|sentry|tramado\.app/i);
  });
});

describe('groupActivity', () => {
  const e = (at: string, action: string | null, classId: string | null, extra: Partial<{ model: string; passages: number; code: string }> = {}) => ({
    at, action, classId, model: extra.model ?? 'google/gemma-4-31b-it:free', passages: extra.passages ?? 0, code: extra.code ?? null,
  });
  it('groups consecutive requests of one action and class within 60 s', () => {
    const rows = groupActivity([
      e('2026-11-03T15:20:50Z', 'examAnswer', 'law', { passages: 9 }),
      e('2026-11-03T15:20:10Z', 'examAnswer', 'law', { passages: 12, model: 'google/gemma-4-26b-a4b-it:free' }),
      e('2026-11-03T15:19:40Z', 'examAnswer', 'law', { code: 'AI_BUSY' }),
      e('2026-11-03T15:19:30Z', 'ask', 'law'),
      e('2026-11-03T15:10:00Z', 'ask', 'law'),
      e('2026-11-03T15:09:59Z', 'keyCheck', null),
    ]);
    expect(rows.map((r) => [r.action, r.requests])).toEqual([['examAnswer', 3], ['ask', 1], ['ask', 1], ['keyCheck', 1]]);
    expect(rows[0]).toMatchObject({ passages: 12, codes: ['AI_BUSY'], models: ['google/gemma-4-31b-it:free', 'google/gemma-4-26b-a4b-it:free'] });
  });
});
