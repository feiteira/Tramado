// Every way data can leave this computer (UX §3.14.8, Trama's pattern). This single list feeds Settings › Privacy
// ("What leaves this computer") and PRIVACY.md / PRIVACY.pt.md / PRIVACY.es.md (`npm run gen:privacy`), so the two
// cannot drift apart. The words are the `privacy` catalog's (EN, PT-PT, ES); this file says which flows exist, what
// starts them and where they go. A feature that sends anything anywhere must add a flow here (and its catalog row).
//
// What the code does, flow by flow (checked when this list changes):
//   sharing     Syncthing (crates/tramado-sync): started only once a class is shared or joined (C6); global
//               discovery, relays, NAT traversal and local announcements unless "Local network only"; usage
//               reporting (urAccepted -1), crash reporting and auto-upgrade are off (managed.rs).
//   joinPage    not Tramado itself: a browser opening an invite's web link or QR code (core/sync/invite.ts JOIN_PAGE)
//               loads site/join/index.html from GitHub Pages; the code stays in the '#' fragment, which browsers never
//               send, and the page makes no request of its own (its CSP is default-src 'none').
//   keyCheck    AiService `GET key` (free requests left; the key only) when the AI pill starts and again after 15 min
//               away, and when a key is tested; `GET models` (the catalog) at most once a day — only with a key and AI on.
//   ai          AiClient `chat/completions` through Rust's AiPipe: the question and the passages it needs
//               (services/ask.ts, exams.ts, chat @AI, lecture summary/terms/annotate/study notes, explain).
//   ocr         exam pages / scanned documents as JPEG images (services/exams.ts, documents OCR offer).
//   cloudSpeech tramado-speech `PipeStt`: pieces of ≤ 30 s of the recording, only when cloud transcription is on.
//   customAi    the same requests as `ai`/`ocr`, to the address entered in Settings › AI › Another service.
//   model       tramado-speech downloads from huggingface.co (models and the VAD), only when asked to.
import type { Messages } from '../i18n/catalogs';
import { catalogs } from '../i18n/catalogs';
import { UI_LOCALES, UI_LOCALE_META, type UiLocale } from '../i18n/languages';

export const FLOW_IDS = ['nothing', 'sharing', 'joinPage', 'keyCheck', 'ai', 'ocr', 'cloudSpeech', 'customAi', 'model', 'never'] as const;
export type FlowId = (typeof FLOW_IDS)[number];

export interface Flow {
  id: FlowId;
  /** 'none': nothing is sent ("Nothing set up", "Never"); 'setting': happens by itself once set up; 'action': only when you do it. */
  trigger: 'none' | 'setting' | 'action';
  /** Hosts contacted (documentation; the catalog row says it in words). */
  hosts: readonly string[];
}

export const FLOWS: readonly Flow[] = [
  { id: 'nothing', trigger: 'none', hosts: [] },
  { id: 'sharing', trigger: 'setting', hosts: ['classmates’ computers', 'discovery-v4.syncthing.net', 'relays.syncthing.net', 'Syncthing STUN servers', 'local network'] },
  { id: 'joinPage', trigger: 'action', hosts: ['feiteira.github.io (GitHub Pages)'] },
  { id: 'keyCheck', trigger: 'setting', hosts: ['openrouter.ai'] },
  { id: 'ai', trigger: 'action', hosts: ['openrouter.ai', 'the model’s provider'] },
  { id: 'ocr', trigger: 'action', hosts: ['openrouter.ai', 'the model’s provider'] },
  { id: 'cloudSpeech', trigger: 'action', hosts: ['openrouter.ai', 'the speech model’s provider'] },
  { id: 'customAi', trigger: 'action', hosts: ['the address you entered'] },
  { id: 'model', trigger: 'action', hosts: ['huggingface.co'] },
  { id: 'never', trigger: 'none', hosts: [] },
];

export interface FlowText { when: string; what: string; to: string }

/** A flow's words in a language. */
export function flowText(id: FlowId, locale: UiLocale): FlowText {
  return (catalogs[locale] as Messages).privacy.rows[id];
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

/** PRIVACY.md (en) / PRIVACY.pt.md / PRIVACY.es.md: the table of Settings › Privacy, in one language. */
export function privacyMarkdown(locale: UiLocale): string {
  const m = catalogs[locale] as Messages;
  const p = m.privacy;
  const others = UI_LOCALES.filter((l) => l !== locale)
    .map((l) => `[${UI_LOCALE_META[l].nativeName}](${l === 'en' ? 'PRIVACY.md' : `PRIVACY.${l}.md`})`)
    .join(' · ');
  const lines = [
    `# ${p.title}`,
    '',
    '<!-- Generated by `npm run gen:privacy` from app/src/core/privacy/flows.ts and the `privacy` catalog. Do not edit by hand. -->',
    '',
    others,
    '',
    p.intro,
    '',
    `| ${p.columns.when} | ${p.columns.what} | ${p.columns.to} |`,
    '|---|---|---|',
    ...FLOWS.map((f) => {
      const r = p.rows[f.id];
      return `| ${cell(r.when)} | ${cell(r.what)} | ${cell(r.to)} |`;
    }),
    '',
    `## ${p.log.title}`,
    '',
    p.log.intro,
    '',
    `## ${p.where.title}`,
    '',
    p.whereBody,
    '',
  ];
  return lines.join('\n');
}

/** The file name of a language's privacy document at the repository root. */
export const privacyFile = (locale: UiLocale): string => (locale === 'en' ? 'PRIVACY.md' : `PRIVACY.${locale}.md`);
